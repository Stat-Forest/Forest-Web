export type YashilKey = keyof typeof DICT;

export const yashilText = (key: YashilKey, script: Script): string => {
  const entry = DICT[key] as Entry | undefined;
  if (!entry) return key;
  return script === "ru" ? entry[2] : entry[1];
};

// Backend hozircha ba'zi yorliqlarni faqat kirillda beradi (unit_cyr, state_cyr, route_cyr, label_cyr …)
const BY_CYR = new Map<string, YashilKey>();
for (const [k, v] of Object.entries(DICT) as [YashilKey, Entry][]) if (!BY_CYR.has(v[0])) BY_CYR.set(v[0], k);

/** Backend'ning kirill yorlig'ini joriy tilga o'giradi; lug'atda bo'lmasa o'zini qaytaradi. «2026 баҳор» kabi yil + nom ham. */
export const fromCyr = (text: string | null | undefined, script: Script): string => {
  if (!text) return "";
  const key = BY_CYR.get(text);
  if (key) return yashilText(key, script);
  const m = /^(\d{4}) (.+)$/.exec(text);
  if (m && BY_CYR.has(m[2])) return `${m[1]} ${yashilText(BY_CYR.get(m[2])!, script)}`;
  return text;
};

/** Kalit bo'yicha matn (`t`) va backend kirill yorlig'i (`c`); `script` — joriy til. */
export function useYashilT() {
  const script = useScript();
  const t = useCallback((key: YashilKey) => yashilText(key, script), [script]);
  const c = useCallback((text: string | null | undefined) => fromCyr(text, script), [script]);
  return { t, c, script };
}

/** Backend'dan kelgan `name_cyr`/`name_lat` juftligidan nom: ma'lumotnomalarda rus nomi yo'q — ikkala tilda lotin. */
export const pickName = (obj: { name_cyr: string; name_lat: string }): string =>
  obj.name_lat || obj.name_cyr;

